// Bake one or more harness reports (scores*.json) into src/scores.ts so the
// deployed server is fully self-contained: no file reads, no network, no laptop.
//   node scripts/bake.mjs ../traces/scores.json [more reports...]
import { readFileSync, writeFileSync } from "node:fs";

const inputs = process.argv.slice(2);
if (!inputs.length) {
  console.error("usage: node scripts/bake.mjs <scores.json> [...]");
  process.exit(1);
}
const suites = inputs.map((p) => JSON.parse(readFileSync(p, "utf8")));
for (const s of suites) {
  if (!s.task_category || !Array.isArray(s.servers) || !s.servers.length) {
    throw new Error(`not a harness report: missing task_category/servers`);
  }
}
const out =
  "// GENERATED by scripts/bake.mjs from real harness runs. Do not hand-edit scores.\n" +
  'import type { Suite } from "./types.js";\n\n' +
  `export const SUITES: Suite[] = ${JSON.stringify(suites, null, 2)};\n`;
writeFileSync(new URL("../src/scores.ts", import.meta.url), out);
for (const s of suites) {
  console.log(`baked ${s.suite ?? s.task_category} (${s.scored_at}):`);
  for (const v of s.servers) console.log(`  ${String(v.score).padStart(4)}  ${v.id}`);
}
